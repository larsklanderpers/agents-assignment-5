"""Grounding evidence kept separate from the answer being evaluated."""
from copy import deepcopy
from backend.config import (
    BUDGET_CEILING, DEPARTMENT_BUDGETS, HIGH_RISK_THRESHOLD, MEDIUM_RISK_THRESHOLD,
)


def workflow_record(state, path):
    """Capture recorded facts, excluding explanations that still need judging."""
    record = {key: deepcopy(state.get(key)) for key in (
        "status", "risk_level", "is_valid", "validation_message", "department_budget", "budget_remaining", "within_budget",
    ) if key in state}
    record.update(approval_path=list(path), human_reviews=len(state.get("decisions", [])))
    record["risk_reasoning_provided"] = bool(state.get("risk_reasoning"))
    record["decisions"] = [
        {key: deepcopy(decision[key]) for key in
         ("stage", "decision", "approved", "reviewer", "timestamp") if key in decision}
        for decision in state.get("decisions", [])
    ]
    return record


def policy_record():
    """Authoritative configuration, never generated by the candidate answer."""
    return {
        "budget_ceiling": BUDGET_CEILING,
        "department_budgets": dict(DEPARTMENT_BUDGETS),
        "valid_departments": list(DEPARTMENT_BUDGETS),
        "input_validation": "The amount must be positive and at or below the ceiling; the department must be valid.",
        "risk_rules": {
            "low": f"amount <= {MEDIUM_RISK_THRESHOLD}",
            "medium": f"{MEDIUM_RISK_THRESHOLD} < amount <= {HIGH_RISK_THRESHOLD}",
            "high": f"{HIGH_RISK_THRESHOLD} < amount <= {BUDGET_CEILING}",
            "critical": f"priority urgent and amount > {HIGH_RISK_THRESHOLD}",
        },
        "routing": (
            "Low: budget validation, then approval if within budget; otherwise manager. "
            "Medium: manager, then budget validation; over budget adds finance. "
            "High: manager then finance. Critical: manager then finance then executive. "
            "Any human rejection ends the request. Invalid inputs are rejected before risk assessment."
        ),
        "evidence_limits": (
            "Request fields are requester-reported claims, not independent verification. "
            "Urgent priority alone does not establish an outage. Department budgets are "
            "configured references, not live accounting balances. "
            "Review submissions are recorded human statements. A decision's reasoning "
            "copies that reviewer's comment. Attribution of a comment can be verified "
            "against its submission, but its contents are not authoritative policy "
            "or independently verified business facts."
        ),
    }
